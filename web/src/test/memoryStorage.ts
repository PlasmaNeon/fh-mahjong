/**
 * A `Storage` implementation backed by a Map. The node test environment has no
 * `window`, so tests that exercise localStorage-backed helpers stub one with
 * this; a fresh store per test keeps round-trip cases isolated without jsdom.
 */
export function createMemoryStorage(): Storage {
  const store = new Map<string, string>()
  return {
    get length() {
      return store.size
    },
    clear: () => store.clear(),
    getItem: (key: string) => (store.has(key) ? store.get(key)! : null),
    key: (index: number) => Array.from(store.keys())[index] ?? null,
    removeItem: (key: string) => {
      store.delete(key)
    },
    setItem: (key: string, value: string) => {
      store.set(key, String(value))
    },
  }
}
